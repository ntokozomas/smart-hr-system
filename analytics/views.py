import csv

from django.http import Http404, HttpResponse
from django.shortcuts import render
from django.utils import timezone

from accounts.audit import log_action
from accounts.permissions import require_permission, role_name

from .charts import absenteeism_chart, leave_chart
from .forms import ReportFilterForm
from .metrics import report_tables
from .pdf import report_pdf
from .services import load_report

REPORT_TITLE = "Leave and absenteeism report"
EXPORT_FORMATS = ("csv", "pdf")


def _run_report(request, form):
    data = form.cleaned_data
    return load_report(
        request.user,
        data["start_date"],
        data["end_date"],
        department=data.get("department"),
        leave_type=data.get("leave_type", ""),
    )


def _details(request, form):
    data = form.cleaned_data
    user = request.user
    generated_by = user.get_full_name() or user.username
    role = role_name(user)
    if role:
        generated_by = f"{generated_by} ({role})"
    return [
        ("Period", f"{data['start_date']:%d %b %Y} to {data['end_date']:%d %b %Y}"),
        ("Department", form.department_label()),
        ("Leave type", form.leave_type_label()),
        ("Generated", f"{timezone.localtime():%d %b %Y %H:%M}"),
        ("Generated by", generated_by),
    ]


@require_permission("reports.view")
def reports(request):
    form = ReportFilterForm(request.GET, user=request.user)
    context = {"form": form, "query": request.GET.urlencode()}
    if form.is_valid():
        report = _run_report(request, form)
        context.update(
            {
                "report": report,
                "details": _details(request, form),
                "tables": report_tables(report),
                "leave_chart": leave_chart(report),
                "absenteeism_chart": absenteeism_chart(report),
            }
        )
    return render(request, "analytics/reports.html", context)


@require_permission("reports.view")
def export_report(request, file_format):
    if file_format not in EXPORT_FORMATS:
        raise Http404
    form = ReportFilterForm(request.GET, user=request.user)
    if not form.is_valid():
        raise Http404
    report = _run_report(request, form)
    details = _details(request, form)
    tables = report_tables(report)
    filename = f"smart-hr-report-{report.start:%Y%m%d}-{report.end:%Y%m%d}.{file_format}"

    if file_format == "csv":
        response = HttpResponse(content_type="text/csv; charset=utf-8")
        response.write("\ufeff")
        writer = csv.writer(response)
        writer.writerow([REPORT_TITLE])
        for label, value in details:
            writer.writerow([label, value])
        for heading, headers, rows in tables:
            writer.writerow([])
            writer.writerow([heading])
            writer.writerow(headers)
            writer.writerows(rows)
    else:
        response = HttpResponse(
            report_pdf(REPORT_TITLE, details, tables), content_type="application/pdf"
        )

    response["Content-Disposition"] = f'attachment; filename="{filename}"'
    log_action(
        "Export",
        f"Exported the {REPORT_TITLE.lower()} as {file_format.upper()} "
        f"({details[0][1]}, {details[1][1]})",
    )
    return response
